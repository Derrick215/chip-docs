// Optional integration check: requires playwright-core and a local Chrome installation.
const { chromium } = require(process.env.PLAYWRIGHT_CORE || 'playwright-core');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const waitRendered = (number) => page.locator(`#pdf-pages .pdf-page[data-page="${number}"].is-rendered`).waitFor({ timeout: 60000 });
    const errors = [];
    const pdfRequests = [];
    page.on('pageerror', (error) => errors.push(error.stack || error.message));
    page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
    page.on('request', (request) => { if (/\.pdf(?:\?|$)/i.test(request.url())) pdfRequests.push(request.url()); });
    await page.goto('http://localhost:8000');
    assert.equal(await page.locator('.document-card').count(), 16);
    assert.equal(await page.locator('#model-count').textContent(), '8');
    assert.equal(await page.locator('#file-count').textContent(), '20');
    await page.locator('#document-type').selectOption('DS');
    assert.equal(await page.locator('.document-card').count(), 8);
    await page.locator('#search').fill('LE1');
    assert.equal(await page.locator('.document-card').count(), 1);
    assert.ok(await page.locator('.document-card').innerText().then((text) => text.includes('v1.6')));
    await page.locator('#latest-only').uncheck();
    assert.equal(await page.locator('.document-card').count(), 2);
    await page.locator('#search').fill('');
    await page.locator('#latest-only').check();
    await page.locator('#document-type').selectOption('RM');
    assert.equal(await page.locator('.document-card').count(), 8);
    await page.locator('#document-type').selectOption('all');
    assert.equal(pdfRequests.length, 0, 'The catalog must not preload PDFs');
    await page.locator('#search').fill('MD1');
    assert.equal(await page.locator('.document-card').count(), 2);
    await page.locator('#latest-only').uncheck();
    assert.equal(await page.locator('.document-card').count(), 3);
    await page.locator('#search').fill('no-such-model');
    assert.equal(await page.locator('#empty-state').isVisible(), true);
    await page.locator('#reset-filters').click();
    await page.getByRole('button', { name: 'LE 系列', exact: true }).click();
    assert.equal(await page.locator('.document-card').count(), 4);
    await page.getByRole('button', { name: '全部系列', exact: true }).click();
    const output = path.resolve(__dirname, '../.preview');
    fs.mkdirSync(output, { recursive: true });
    await page.screenshot({ path: path.join(output, 'desktop.png'), fullPage: true });
    const documents = await page.evaluate(() => window.DOCUMENTS);
    assert.equal(documents.length, 20);
    assert.equal(documents.filter((doc) => doc.type === 'DS').length, 9);
    for (const doc of documents) {
      await page.evaluate((id) => { location.hash = new URLSearchParams({doc: id, page: '1'}).toString(); }, doc.id);
      await waitRendered(1);
      assert.equal(await page.locator('#reader-title').textContent(), `${doc.model} ${doc.title}`);
      await page.waitForFunction(() => !document.getElementById('next-page').disabled);
      const total = await page.locator('#page-total').textContent();
      assert.match(total, /\/ \d+/);
      assert.equal(await page.locator('.pdf-page[data-page="1"] canvas').evaluate((canvas) => canvas.width > 0 && canvas.height > 0), true);
      assert.equal(await page.locator('.pdf-page').count(), Number(total.slice(2)), 'Every page must have a scroll position');
      console.log(`${doc.filename}: ${total.slice(2)} pages, rendered`);
      await page.locator('#reader-close').click();
    }
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Mobile catalog overflows');
    await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true });
    await page.locator('#document-type').selectOption('RM');
    await page.locator('.card-action').first().click();
    await waitRendered(1);
    await page.waitForFunction(() => !document.getElementById('next-page').disabled);
    await page.locator('#next-page').click();
    await page.waitForFunction(() => document.getElementById('page-number').value === '2' && !document.getElementById('next-page').disabled);
    await waitRendered(2);
    await page.locator('#page-number').fill('25');
    await page.locator('#page-number').press('Enter');
    await page.waitForFunction(() => document.getElementById('page-number').value === '25' && !document.getElementById('next-page').disabled);
    await waitRendered(25);
    await page.locator('#page-scroll').evaluate((element) => { element.scrollTop += 1200; });
    await page.waitForFunction(() => Number(document.getElementById('page-number').value) > 25);
    await page.locator('#zoom').selectOption('1.25');
    await page.waitForFunction(() => !document.getElementById('next-page').disabled);
    await page.locator('#zoom').selectOption('fit');
    await page.waitForFunction(() => !document.getElementById('next-page').disabled);
    await page.locator('#outline-toggle').click();
    assert.equal(await page.locator('#outline-panel').isVisible(), true);
    await page.locator('#outline-content .outline-link[data-page]').first().waitFor();
    assert.equal(await page.locator('#outline-content').innerText().then((text) => text.includes('展开子章节')), false);
    const firstArrow = page.locator('#outline-content .outline-arrow:not([disabled])').first();
    await firstArrow.click();
    assert.equal(await firstArrow.getAttribute('aria-expanded'), 'true');
    const outlinePage = await page.locator('#outline-content .outline-link[data-page]').first().getAttribute('data-page');
    await page.locator('#outline-content .outline-link[data-page]').first().click();
    await page.locator('#outline-panel').waitFor({ state: 'hidden' });
    await page.waitForFunction(() => !document.getElementById('next-page').disabled);
    assert.equal(await page.locator('#outline-panel').isVisible(), false);
    await waitRendered(outlinePage);
    await page.screenshot({ path: path.join(output, 'mobile-reader.png') });
    await page.locator('#page-number').fill('800');
    await page.locator('#page-number').press('Enter');
    await waitRendered(800);
    assert.ok(await page.locator('.pdf-page canvas').count() <= 8, 'Offscreen canvases must be released');
    await page.locator('#find-toggle').click();
    await page.locator('#find-input').fill('GPIO');
    await page.locator('#find-form').evaluate((form) => form.requestSubmit());
    await page.waitForFunction(() => document.getElementById('find-summary').textContent.startsWith('检索完成'), null, { timeout: 120000 });
    assert.ok(await page.locator('.find-result').count() > 0);
    assert.equal(await page.locator('.find-result mark').first().textContent().then((text) => text.toLowerCase()), 'gpio');
    await page.screenshot({ path: path.join(output, 'mobile-search.png') });
    const foundPage = await page.locator('.find-result').first().getAttribute('data-page');
    await page.locator('.find-result').first().click();
    await waitRendered(foundPage);
    await page.locator(`.pdf-page[data-page="${foundPage}"] .pdf-match.selected`).first().waitFor();
    assert.ok(await page.locator(`.pdf-page[data-page="${foundPage}"] .pdf-match`).count() > 1, 'All occurrences on the page should be highlighted');
    assert.equal(await page.locator('#page-number').inputValue(), foundPage);
    await page.locator('#find-toggle').click();
    const second = page.locator(`.find-result[data-page="${foundPage}"]`).nth(1);
    const secondId = (await second.getAttribute('data-id')).split(':')[1];
    await second.click();
    await page.locator(`.pdf-page[data-page="${foundPage}"] .pdf-match.selected[data-match="${secondId}"]`).first().waitFor();
    await page.locator('#zoom').selectOption('1.25');
    await waitRendered(foundPage);
    await page.locator(`.pdf-page[data-page="${foundPage}"] .pdf-match.selected[data-match="${secondId}"]`).first().waitFor();
    await page.locator('#zoom').selectOption('fit');
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.locator('#find-toggle').click();
    if (await page.locator('#find-more').isVisible()) await page.locator('#find-more').click();
    const target = page.locator('.find-result[data-page="541"]').first();
    await target.click();
    await waitRendered(541);
    await page.locator('.pdf-page[data-page="541"] .pdf-match.selected').first().waitFor();
    assert.equal(await page.locator('.pdf-page[data-page="541"] .pdf-match.selected').first().getAttribute('data-text'), 'GPIO');
    assert.ok(await page.locator('.pdf-page[data-page="541"]').evaluate((element) => Math.abs(element.querySelector('.textLayer').getBoundingClientRect().width - element.querySelector('canvas').getBoundingClientRect().width) < 1), 'Text layer must use the same scale as the PDF canvas');
    assert.ok(await page.locator('#find-input').evaluate((element) => element.getBoundingClientRect().top >= document.querySelector('.reader-toolbar').getBoundingClientRect().bottom), 'Search controls must stay visible above the result list');
    assert.ok(await page.locator('.find-result').first().evaluate((element) => element.offsetHeight <= 40), 'Search rows should stay compact');
    await page.screenshot({ path: path.join(output, 'desktop-search-highlight.png') });
    await page.locator('#page-number').fill('800');
    await page.locator('#page-number').press('Enter');
    await waitRendered(800);
    await target.click();
    await waitRendered(541);
    await page.locator('.pdf-page[data-page="541"] .pdf-match.selected').first().waitFor();
    await page.locator('#find-input').fill('no-such-keyword-ytm-392023');
    assert.equal(await page.locator('.pdf-match').count(), 0, 'Editing the query must clear old highlights');
    await page.locator('#find-input').press('Enter');
    await page.waitForFunction(() => document.getElementById('find-summary').textContent.startsWith('检索完成'));
    assert.equal(await page.locator('.find-result').count(), 0);
    await page.locator('#reader-close').click();
    await page.locator('#clear-recent').click();
    assert.equal(await page.locator('#recent-section').isVisible(), false);
    assert.deepEqual(errors, []);
    console.log('PASS: catalog, all PDFs, scrolling, outline, compact occurrence list, PDF highlights, exact match navigation, zoom/re-render persistence, query clearing; no browser errors.');
  } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
