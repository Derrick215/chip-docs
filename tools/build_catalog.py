"""Rebuild the static document catalog. Run from any working directory."""
import json
import re
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
PATTERN = re.compile(r"(?P<model>YTM32B1(?P<family>[A-Z]{2})\d+x)_(?P<type>RM|DS)_v?(?P<version>\d+(?:\.\d+)*)\.pdf", re.I)


def main():
    documents = []
    paths = sorted(path for folder in ("RM", "DS") for path in (ROOT / folder).glob("*.pdf"))
    for path in paths:
        match = PATTERN.fullmatch(path.name)
        if not match:
            raise SystemExit(f"Unsupported filename: {path.name}; expected MODEL_RM_v1.0.pdf or MODEL_DS_v1.0.pdf")
        doc_type = match["type"].upper()
        if path.parent.name != doc_type:
            raise SystemExit(f"Document type does not match directory: {path}")
        documents.append({
            "id": path.stem,
            "model": match["model"],
            "family": match["family"].upper(),
            "type": doc_type,
            "title": "数据手册" if doc_type == "DS" else "参考手册",
            "version": match["version"],
            "filename": path.name,
            "url": doc_type + "/" + quote(path.name),
            "bytes": path.stat().st_size,
        })
    if not documents:
        raise SystemExit("No PDF files found in RM/ or DS/; existing catalog was not changed.")
    content = "// Generated by tools/build_catalog.py.\nwindow.DOCUMENTS = " + json.dumps(documents, ensure_ascii=False, indent=2) + ";\n"
    (ROOT / "documents.js").write_text(content, encoding="utf-8")
    print(f"Catalog updated: {len(documents)} documents, {len(set(d['model'] for d in documents))} models.")


if __name__ == "__main__":
    main()
